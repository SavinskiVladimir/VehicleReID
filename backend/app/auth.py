"""
Ограничение доступа к административным функциям системы (ТЗ п.1.1.2.4,
требования по безопасности: "доступ к административным функциям
системы (добавление/удаление записей базы данных) должен быть
ограничен посредством механизма ролей").

СОЗНАТЕЛЬНОЕ УПРОЩЕНИЕ ОБЪЁМА РАБОТЫ: полноценная система
пользователей/ролей (регистрация, вход, хранение паролей, сессии) -
отдельная по объёму задача, не являющаяся предметом данной работы
(акцент сделан на ML-часть системы, см. ТЗ п.1.1.1.1). Вместо этого
реализован единый секретный токен администратора (общий "пароль" для
всех, кто должен иметь доступ к admin-функциям) - минимальный
механизм, формально удовлетворяющий требованию "доступ ограничен", без
полноценной инфраструктуры ролей/пользователей. При дальнейшем
развитии системы эта функция - естественная точка расширения до
полноценной ролевой модели (например, через OAuth2/JWT), сама
dependency-функция ниже используется одинаково независимо от того, как
именно реализована проверка внутри.
"""

from __future__ import annotations

import secrets

from fastapi import Header, HTTPException, Request, status


async def require_admin(request: Request, x_admin_token: str = Header(...)) -> None:
    """
    FastAPI-dependency: подключается к admin-эндпоинтам
    (добавление/удаление наблюдений) через Depends(require_admin).

    Ожидает заголовок X-Admin-Token, совпадающий с settings.admin_api_key.
    Сравнение через secrets.compare_digest - защита от timing-атак
    (обычное `==` для сравнения секретов теоретически уязвимо к
    восстановлению значения по времени сравнения строк посимвольно).

    Сравниваются БАЙТЫ, а не строки: compare_digest для str с не-ASCII
    символами бросает TypeError, и запрос с таким заголовком (например,
    токеном кириллицей) получал бы 500 вместо 403.
    """
    settings = request.app.state.settings

    provided = x_admin_token.encode("utf-8")
    expected = settings.admin_api_key.encode("utf-8")
    if not secrets.compare_digest(provided, expected):
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Недостаточно прав для выполнения этой операции.",
        )